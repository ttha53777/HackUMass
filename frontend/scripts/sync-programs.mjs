// Regenerates two small tables for the front pages from the backend's data, so they stay true:
//  - src/components/front/landing/program-count.ts from backend/app/data/programs/
//  - src/components/front/chat/zips.ts (ZIP code -> town) from backend/app/data/regions.json
import { readFileSync, readdirSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const data = resolve(here, "../../backend/app/data");
const header = (from) => `// GENERATED by \`npm run sync:programs\` from backend/app/data/${from}.\n// Do not edit by hand.\n\n`;

const countTarget = resolve(here, "../src/components/front/landing/program-count.ts");
const count = readdirSync(resolve(data, "programs")).filter((f) => f.endsWith(".json")).length;
writeFileSync(
  countTarget,
  header("programs/") + "/** How many programs are in the hand-checked list. */\n" + `export const PROGRAM_COUNT = ${count};\n`,
);
console.log(`Wrote ${countTarget} (${count} programs)`);

const zipTarget = resolve(here, "../src/components/front/chat/zips.ts");
const regions = JSON.parse(readFileSync(resolve(data, "regions.json"), "utf8"));
const zips = Object.fromEntries(Object.entries(regions.supported_zips).map(([zip, r]) => [zip, r.city]));
writeFileSync(
  zipTarget,
  header("regions.json") +
    "/** The ZIP codes the backend covers, and the town each belongs to. */\n" +
    `export const ZIPS: Record<string, string> = ${JSON.stringify(zips, null, 2)};\n`,
);
console.log(`Wrote ${zipTarget} (${Object.keys(zips).length} ZIP codes)`);
