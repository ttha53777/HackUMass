// Writes the FICTIONAL demo papers from the one source of truth,
// backend/tests/fixtures/demo_person.json. No real people, accounts or addresses.
//
// Output, under public/demo-papers/<slug>/:
//   <paper>.pdf and <paper>.txt   each paper, as a text PDF and plain text (same lines)
//   manifest.json                 paper -> kind, title, files (what the Demo kit lists)
//   profile-sheet.txt             copy-paste answers for the chat and the forms
// and backend/tests/fixtures/demo_papers_expected.json, the facts each paper must
// extract (checked by backend/tests/test_demo_papers.py).
//
// Run: node scripts/make-demo-papers.mjs
import { mkdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const sourcePath = resolve(here, "../../backend/tests/fixtures/demo_person.json");
const expectedPath = resolve(here, "../../backend/tests/fixtures/demo_papers_expected.json");
const demo = JSON.parse(readFileSync(sourcePath, "utf8"));
const root = resolve(here, "../public/demo-papers");
const out = resolve(root, demo.slug);

const SAMPLE = "SAMPLE DOCUMENT - FICTIONAL - FOR A DEMO ONLY";

/** A one-page PDF of text lines (Helvetica), readable by any PDF text extractor. */
function pdf(title, lines) {
  const esc = (s) => s.replace(/\\/g, "\\\\").replace(/\(/g, "\\(").replace(/\)/g, "\\)");
  const body = [
    "BT /F2 9 Tf 72 760 Td (" + esc(SAMPLE) + ") Tj ET",
    "BT /F1 18 Tf 72 726 Td (" + esc(title) + ") Tj ET",
    ...lines.map((line, i) => `BT /F2 11 Tf 72 ${690 - i * 18} Td (${esc(line)}) Tj ET`),
  ].join("\n");
  const objects = [
    "<< /Type /Catalog /Pages 2 0 R >>",
    "<< /Type /Pages /Kids [3 0 R] /Count 1 >>",
    "<< /Type /Page /Parent 2 0 R /MediaBox [0 0 612 792] /Resources << /Font << /F1 4 0 R /F2 5 0 R >> >> /Contents 6 0 R >>",
    "<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica-Bold >>",
    "<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica >>",
    `<< /Length ${Buffer.byteLength(body)} >>\nstream\n${body}\nendstream`,
  ];
  let doc = "%PDF-1.4\n";
  const offsets = [];
  objects.forEach((o, i) => {
    offsets.push(Buffer.byteLength(doc));
    doc += `${i + 1} 0 obj\n${o}\nendobj\n`;
  });
  const xref = Buffer.byteLength(doc);
  doc += `xref\n0 ${objects.length + 1}\n0000000000 65535 f \n`;
  doc += offsets.map((o) => `${String(o).padStart(10, "0")} 00000 n \n`).join("");
  doc += `trailer\n<< /Size ${objects.length + 1} /Root 1 0 R >>\nstartxref\n${xref}\n%%EOF\n`;
  return doc;
}

// Start clean so a removed paper doesn't linger (the old flat files included).
rmSync(root, { recursive: true, force: true });
mkdirSync(out, { recursive: true });

const manifest = { _comment: "FICTIONAL demo papers. Generated; do not edit by hand.", slug: demo.slug, person: demo.person.full_name, papers: [] };
const expected = { _comment: "Generated by frontend/scripts/make-demo-papers.mjs from demo_person.json. Do not edit by hand.", papers: {}, details: {} };

for (const paper of demo.papers) {
  const text = [SAMPLE, paper.title, ...paper.lines].join("\n") + "\n";
  writeFileSync(resolve(out, `${paper.file}.pdf`), pdf(paper.title, paper.lines));
  writeFileSync(resolve(out, `${paper.file}.txt`), text);
  manifest.papers.push({
    file: paper.file,
    title: paper.title,
    kinds: [paper.kind, ...(paper.also ?? [])],
    pdf: `${paper.file}.pdf`,
    txt: `${paper.file}.txt`,
    ...(paper.household_member ? { household_member: paper.household_member } : {}),
  });
  expected.papers[paper.file] = paper.expected ?? {};
  // Form details the paper gives the device when read as its own kind (fill-sheet key -> value).
  expected.details[paper.file] = paper.expected_details ?? {};
}

const p = demo.person;
const c = demo.chat;
const sheet = [
  "OPENDOOR DEMO PROFILE - FICTIONAL",
  "",
  `${p.full_name}, ZIP ${c.zip}. Household on paper: ${demo.household.length} people (${demo.household.map((h) => `${h.name.split(" ")[0]}, born ${h.born}`).join("; ")}).`,
  "",
  "1. Paste into the chat's first question:",
  `   ${c.message}`,
  "",
  "2. Answer the chat questions:",
  `   ZIP code: ${c.zip}`,
  `   How many people live with you: ${c.typed_household_size}   <- the deliberate mismatch; the household paper says ${demo.household.length}`,
  "   Does anyone at home fit any of these: A child under 5 or a pregnancy",
  "   Housing: I rent",
  "",
  "3. Papers page: Add all demo papers. Each paper is read as its own kind.",
  "   The household paper should raise: \"Your document shows a household of 3...\"",
  "",
  `4. Bank (Your money -> Connect a bank): ${c.bank_persona.replace(/-/g, " ")}.`,
  "",
  "5. Details for forms (Fill this in with me):",
  `   First name: ${p.first_name}`,
  `   Last name: ${p.last_name}`,
  `   Date of birth: ${p.date_of_birth}`,
  `   Street address: ${p.street_address}`,
  `   City: ${p.city}   State: ${p.state}   ZIP: ${p.zip}`,
  `   Phone: ${p.phone}`,
  `   Email: ${p.email}`,
  "",
  "6. The one thing no paper covers (the form helper asks for it):",
  ...Object.entries(demo.form_extra ?? {}).map(([k, v]) => `   ${k.replace(/_/g, " ")}: ${v}`),
  "",
].join("\n");

writeFileSync(resolve(out, "manifest.json"), JSON.stringify(manifest, null, 2) + "\n");
writeFileSync(resolve(out, "profile-sheet.txt"), sheet);
writeFileSync(expectedPath, JSON.stringify(expected, null, 2) + "\n");
console.log(`Wrote ${demo.papers.length} fictional papers (PDF + text), manifest and profile sheet to ${out}`);
